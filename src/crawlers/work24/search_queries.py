def get_all_queries() -> list[str]:
    """WORK24_SEARCH_QUERIES 의 모든 검색어를 중복 없이 평탄화해 반환한다."""
    seen: set[str] = set()
    result: list[str] = []
    for queries in WORK24_SEARCH_QUERIES.values():
        for q in queries:
            if q not in seen:
                seen.add(q)
                result.append(q)
    return result


def get_queries_for_function(function_name: str) -> list[str]:
    """taxonomy 직무명에 매핑된 고용24 검색어 목록을 반환한다."""
    return WORK24_SEARCH_QUERIES.get(function_name, [])


def get_function_for_query(query: str) -> str:
    """
    검색어에서 job_function_name을 역매핑한다.
    없으면 빈 문자열을 반환한다.
    """
    for func, queries in WORK24_SEARCH_QUERIES.items():
        if query in queries:
            return func
    return ""
